        "4. 识别通用性强：支持任意角落的按钮、支持叉号等纯图标按钮、支持带倒计时且数字位置不定的按钮；",
        "5. 多重防误触：从包名、时间、次数、冷却、关键词、位置、尺寸、敏感词到二次校验逐层收敛；",
        "6. 可观测：完整的日志与节点调试工具，识别失败时能明确定位原因；",
